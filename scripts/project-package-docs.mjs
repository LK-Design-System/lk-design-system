function invariant(condition, message) {
  if (!condition) throw new Error(message);
}

async function exists(file) {
  try {
    await access(file);
    return true;
  } catch {
    return false;
  }
}

function posixPath(value) {
  return value.replaceAll('\\', '/');
}

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}

async function read(relativePath) {
  return readFile(path.join(root, relativePath));
}

async function readText(relativePath) {
  return (await read(relativePath)).toString('utf8');
}

async function readJson(relativePath) {
  return JSON.parse(await readText(relativePath));
}

async function walkFiles(directory) {
  if (!(await exists(directory))) return [];
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walkFiles(full));
    else files.push(full);
  }
  return files;
}

async function inventory(directory) {
  const files = await walkFiles(directory);
  const rows = [];
  let bytes = 0;
  for (const file of files.sort((a, b) => a.localeCompare(b))) {
    const contents = await readFile(file);
    const relative = posixPath(path.relative(directory, file));
    bytes += contents.byteLength;
    rows.push(`${relative}|${contents.byteLength}|${sha256(contents)}`);
  }
  return {
    fileCount: files.length,
    bytes,
    sha256: sha256(rows.join('\n')),
  };
}

function githubSourceUrl(sourcePath, suffix = '', sourceRef = 'main') {
  return `${repositoryUrl}/blob/${sourceRef}/${posixPath(sourcePath)}${suffix}`;
}

function splitHref(href) {
  const match = href.match(/^([^?#]*)([?#].*)?$/);
  return { pathname: match?.[1] ?? href, suffix: match?.[2] ?? '' };
}

function rewriteMarkdownLinks(text, sourcePath, targetPath, sourceToTarget, sourceRef) {
  return text.replace(/(\[[^\]]*\]\()([^)]+)(\))/g, (whole, prefix, rawHref, suffix) => {
    const unwrapped = rawHref.startsWith('<') && rawHref.endsWith('>')
      ? rawHref.slice(1, -1)
      : rawHref;
    if (/^(?:https?:|mailto:|tel:|data:|#)/i.test(unwrapped)) return whole;
    const { pathname, suffix: hrefSuffix } = splitHref(unwrapped);
    if (!pathname) return whole;
    const sourceAbsolute = path.resolve(root, path.dirname(sourcePath), pathname);
    const sourceRelative = posixPath(path.relative(root, sourceAbsolute));
    const projected = sourceToTarget.get(sourceRelative);
    let nextHref;
    if (projected) {
      nextHref = posixPath(path.relative(path.posix.dirname(posixPath(targetPath)), projected));
      if (!nextHref.startsWith('.')) nextHref = `./${nextHref}`;
      nextHref += hrefSuffix;
    } else {
      nextHref = githubSourceUrl(sourceRelative, hrefSuffix, sourceRef);
    }
    return `${prefix}${nextHref}${suffix}`;
  });
}

function relativeProjectedReference(targetPath) {
  const relative = posixPath(path.posix.relative('docs', targetPath));
  return relative.startsWith('.') ? relative : `./${relative}`;
}

function rewriteContractReferences(contract, definition, sourceToTarget, sourceRef) {
  const projectReference = (reference) => {
    const localTarget = sourceToTarget.get(reference);
    if (localTarget) return relativeProjectedReference(localTarget);
    const sharedTarget = sharedReferenceTargets.get(reference);
    if (sharedTarget) return `@lk-design-system/lds-core/${sharedTarget}`;
    if (reference.startsWith(`${canonical.foundationRoot}/`)) {
      return `@lk-design-system/lds-core/docs/foundations/${path.posix.basename(reference)}`;
    }
    return githubSourceUrl(reference, '', sourceRef);
  };
  return {
    ...contract,
    facets: contract.facets.map((facet) => ({
      ...facet,
      references: facet.references.map(projectReference),
    })),
    componentMapping: {
      ...contract.componentMapping,
      references: contract.componentMapping.references.map(projectReference),
    },
  };
}

