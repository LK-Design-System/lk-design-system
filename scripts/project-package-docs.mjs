async function makePackageProjection(definition, canonicalInputs) {
  const packageRoot = path.join(root, 'packages', definition.id);
  const packageManifest = JSON.parse(await readFile(path.join(packageRoot, 'package.json'), 'utf8'));
  invariant(packageManifest.name === definition.name, `${definition.id}: unexpected package name ${packageManifest.name}.`);
  const sourceRef = `lds-v${packageManifest.version}`;

  const sourceToTarget = new Map([
    [canonical.adoptionWorkflow, 'docs/adoption-workflow.md'],
    [canonical.adoptionContract, 'docs/adoption-checklist.json'],
    [canonical.adoptionContractSchema, 'docs/LDS_UI_ADOPTION_CONTRACT.schema.json'],
    [canonical.adoptionReportSchema, 'docs/adoption-report.schema.json'],
    [canonical.adoptionReportExample, 'docs/adoption-report.example.json'],
    [canonical.adoptionWorkflowEvidenceSchema, 'docs/adoption-workflow-evidence.schema.json'],
  ]);
  for (const [sourcePath, targetPath] of [
    [definition.profileSource, definition.profileTarget],
    [definition.familySource, definition.familyTarget],
  ]) {
    if (sourcePath && targetPath) sourceToTarget.set(sourcePath, targetPath);
  }

  const foundationFiles = canonicalInputs.foundationFiles;
  const selectedFoundationSlugs = definition.foundations === 'all'
    ? canonicalInputs.foundationSlugs
    : definition.foundations;
  const selectedFoundationNames = new Set(
    selectedFoundationSlugs.map((slug) => `${slug}.md`),
  );
  if (definition.foundations === 'all') {
    for (const name of [
      'README.md',
      'foundation-content.json',
      'foundation-content.schema.json',
      'TOKEN_REFERENCE.md',
      'llms.txt',
    ]) selectedFoundationNames.add(name);
  }

  if (definition.id === 'core') {
    for (const [sourcePath, targetPath] of sharedReferenceTargets) {
      sourceToTarget.set(sourcePath, targetPath);
    }
    for (const sourcePath of agentSkillFiles) sourceToTarget.set(sourcePath, sourcePath);
  }

  for (const sourcePath of foundationFiles) {
    const name = path.basename(sourcePath);
    if (!selectedFoundationNames.has(name)) continue;
    sourceToTarget.set(sourcePath, `docs/foundations/${name}`);
  }
  if (definition.includeLoadingPattern) {
    sourceToTarget.set(canonical.loadingPattern, 'docs/patterns/loading.md');
  }

  const outputs = new Map();
  const records = [];
  async function projectFile(sourcePath, targetPath) {
    const source = await read(sourcePath);
    const extension = path.extname(sourcePath).toLowerCase();
    const contents = ['.md', '.txt'].includes(extension)
      ? Buffer.from(rewriteMarkdownLinks(source.toString('utf8'), sourcePath, targetPath, sourceToTarget, sourceRef))
      : source;
    outputs.set(targetPath, contents);
    records.push({
      path: targetPath.replace(/^docs\//, ''),
      sha256: sha256(contents),
      sources: [{ path: sourcePath, sha256: sha256(source) }],
    });
    return contents.toString('utf8');
  }

  for (const [sourcePath, targetPath] of [
    [definition.profileSource, definition.profileTarget],
    [definition.familySource, definition.familyTarget],
  ]) {
    if (sourcePath && targetPath) await projectFile(sourcePath, targetPath);
  }

  const workflow = await projectFile(canonical.adoptionWorkflow, 'docs/adoption-workflow.md');
  const canonicalContractSource = await read(canonical.adoptionContract);
  const projectedContract = Buffer.from(`${JSON.stringify(
    rewriteContractReferences(canonicalInputs.adoptionContract, definition, sourceToTarget, sourceRef),
    null,
    2,
  )}\n`);
  outputs.set('docs/adoption-checklist.json', projectedContract);
  records.push({
    path: 'adoption-checklist.json',
    sha256: sha256(projectedContract),
    sources: [{ path: canonical.adoptionContract, sha256: sha256(canonicalContractSource) }],
  });
  await projectFile(canonical.adoptionContractSchema, 'docs/LDS_UI_ADOPTION_CONTRACT.schema.json');
  await projectFile(canonical.adoptionReportSchema, 'docs/adoption-report.schema.json');
  await projectFile(canonical.adoptionWorkflowEvidenceSchema, 'docs/adoption-workflow-evidence.schema.json');
  const canonicalExampleSource = await read(canonical.adoptionReportExample);
  const packageExample = JSON.parse(canonicalExampleSource.toString('utf8'));
  packageExample.$schema = './adoption-report.schema.json';
  const projectedExample = Buffer.from(`${JSON.stringify(packageExample, null, 2)}\n`);
  outputs.set('docs/adoption-report.example.json', projectedExample);
  records.push({
    path: 'adoption-report.example.json',
    sha256: sha256(projectedExample),
    sources: [{ path: canonical.adoptionReportExample, sha256: sha256(canonicalExampleSource) }],
  });

  if (definition.id === 'core') {
    for (const [sourcePath, targetPath] of sharedReferenceTargets) {
      if (!outputs.has(targetPath)) await projectFile(sourcePath, targetPath);
    }
    for (const sourcePath of agentSkillFiles) await projectFile(sourcePath, sourcePath);
  }

  const selectedFoundationTexts = [];
  for (const [sourcePath, targetPath] of [...sourceToTarget.entries()]
    .filter(([sourcePath]) => sourcePath.startsWith(`${canonical.foundationRoot}/`))
    .sort((left, right) => left[1].localeCompare(right[1]))) {
    const projected = await projectFile(sourcePath, targetPath);
    if (selectedFoundationSlugs.some((slug) => sourcePath.endsWith(`/${slug}.md`))) {
      selectedFoundationTexts.push(projected);
    }
  }

  let loading = '';
  if (definition.includeLoadingPattern && !outputs.has('docs/patterns/loading.md')) {
    loading = await projectFile(canonical.loadingPattern, 'docs/patterns/loading.md');
  } else if (definition.includeLoadingPattern) {
    loading = outputs.get('docs/patterns/loading.md').toString('utf8');
  }

  let llms;
  let llmsSources;
  if (definition.includeRootLlms) {
    const source = await read(canonical.rootLlms);
    llms = Buffer.from(rewriteMarkdownLinks(source.toString('utf8'), canonical.rootLlms, 'docs/llms.txt', sourceToTarget, sourceRef));
    llmsSources = [{ path: canonical.rootLlms, sha256: sha256(source) }];
  } else {
    const sections = [workflow, ...selectedFoundationTexts, ...(loading ? [loading] : [])];
    llms = Buffer.from(layerLlms(definition, sections));
    llmsSources = [
      canonical.adoptionWorkflow,
      ...selectedFoundationSlugs.map((slug) => `${canonical.foundationRoot}/${slug}.md`),
      ...(definition.includeLoadingPattern ? [canonical.loadingPattern] : []),
    ].map((sourcePath) => ({
      path: sourcePath,
      sha256: canonicalInputs.sourceHashes.get(sourcePath),
    }));
  }
  outputs.set('docs/llms.txt', llms);
  records.push({ path: 'llms.txt', sha256: sha256(llms), sources: llmsSources });

  const readme = Buffer.from(generatedReadme(definition));
  outputs.set('README.md', readme);

  const adoptionContract = canonicalInputs.adoptionContract;
  const tokenInventory = await inventory(path.join(packageRoot, 'tokens'));
  const assetInventory = await inventory(path.join(packageRoot, 'assets'));
  const publicDocsBase = definition.id === 'core'
    ? storybookUrl
    : `${storybookUrl}packages/${definition.id}/`;
  const generatedSources = new Map();
  for (const record of records) {
    for (const source of record.sources) generatedSources.set(source.path, source.sha256);
  }
  const docsManifest = {
    schemaVersion: 1,
    kind: 'lds-package-documentation',
    package: {
      name: definition.name,
      version: packageManifest.version,
      layer: definition.layer,
    },
    adoption: {
      contractKind: adoptionContract.kind,
      contractVersion: adoptionContract.contractVersion,
      invariant: adoptionContract.invariant,
      facetIds: adoptionContract.facets.map(({ id }) => id),
      componentMappingRequired: Boolean(adoptionContract.componentMapping),
      verdicts: adoptionContract.verdicts,
    },
    entrypoints: {
      llms: './llms.txt',
      adoptionChecklist: './adoption-checklist.json',
      adoptionReportSchema: './adoption-report.schema.json',
      adoptionReportExample: './adoption-report.example.json',
      adoptionWorkflow: './adoption-workflow.md',
      ...(definition.profileContract ? { profileContract: './profile-contract.json' } : {}),
      ...(definition.familyContract ? { familyContract: './product-family-contract.json' } : {}),
      ...(definition.id === 'core' ? { agentSkill: './agent-skills/lds-ui/SKILL.md' } : {}),
    },
    foundations: selectedFoundationSlugs,
    patterns: definition.includeLoadingPattern ? ['loading'] : [],
    publicDocs: {
      storybook: `${storybookUrl}${definition.storybookPath}`,
      llms: `${publicDocsBase}llms.txt`,
      designSystem: definition.id === 'core' ? `${storybookUrl}design-system.json` : `${publicDocsBase}manifest.json`,
      adoptionChecklist: `${publicDocsBase}adoption-checklist.json`,
      adoptionReportSchema: `${publicDocsBase}adoption-report.schema.json`,
      adoptionReportExample: `${publicDocsBase}adoption-report.example.json`,
    },
    source: {
      repository: 'LK-Design-System/lk-design-system',
      ref: sourceRef,
      documents: [...generatedSources.entries()]
        .sort(([left], [right]) => left.localeCompare(right))
        .map(([sourcePath, digest]) => ({ path: sourcePath, sha256: digest })),
    },
    resources: {
      tokens: tokenInventory,
      assets: assetInventory,
    },
    documents: records.sort((left, right) => left.path.localeCompare(right.path)),
  };
  outputs.set('docs/manifest.json', Buffer.from(`${JSON.stringify(docsManifest, null, 2)}\n`));
  return outputs;
}

async function assertCanonicalInputs() {
  for (const sourcePath of Object.values(canonical)) {
    invariant(await exists(path.join(root, sourcePath)), `Canonical package-documentation source is missing: ${sourcePath}`);
  }
  for (const sourcePath of agentSkillFiles) {
    invariant(await exists(path.join(root, sourcePath)), `Canonical agent-skill source is missing: ${sourcePath}`);
  }
  const adoptionContract = await readJson(canonical.adoptionContract);
  invariant(adoptionContract.schemaVersion === 1, 'Adoption contract schemaVersion must be 1.');
  invariant(adoptionContract.kind === 'lds-ui-adoption-contract', 'Unexpected adoption contract kind.');
  invariant(Array.isArray(adoptionContract.facets), 'Adoption contract facets are missing.');
  invariant(
    JSON.stringify(adoptionContract.facets.map(({ id }) => id)) === JSON.stringify(adoptionFacetFields),
    `Adoption contract facet ids must be ${adoptionFacetFields.join(', ')}.`,
  );
  invariant(Array.isArray(adoptionContract.verdicts) && adoptionContract.verdicts.length > 0, 'Adoption contract verdicts are missing.');

  const foundationContent = await readJson(`${canonical.foundationRoot}/foundation-content.json`);
  const foundationSlugs = (foundationContent.foundations ?? []).map(({ slug }) => slug);
  invariant(foundationSlugs.length === 16, `Expected 16 canonical Foundations, found ${foundationSlugs.length}.`);
  const foundationFiles = (await walkFiles(path.join(root, canonical.foundationRoot)))
    .map((file) => posixPath(path.relative(root, file)))
    .sort();
  const sourceHashes = new Map();
  const sourcePaths = new Set([
    ...Object.values(canonical).filter((sourcePath) => !sourcePath.endsWith('foundations')),
    ...sharedReferenceTargets.keys(),
    ...foundationFiles,
  ]);
  for (const sourcePath of sourcePaths) sourceHashes.set(sourcePath, sha256(await read(sourcePath)));
  return { adoptionContract, foundationFiles, foundationSlugs, sourceHashes };
}

async function compareProjection(packageRoot, outputs) {
  const expected = [...outputs.keys()].sort();
  const actual = [
    ...((await exists(path.join(packageRoot, 'README.md'))) ? ['README.md'] : []),
    ...(await walkFiles(path.join(packageRoot, 'docs'))).map((file) => posixPath(path.relative(packageRoot, file))),
  ].sort();
  invariant(
    JSON.stringify(actual) === JSON.stringify(expected),
    `${posixPath(path.relative(root, packageRoot))}: generated documentation file set is stale. Run node scripts/project-package-docs.mjs.`,
  );
  for (const [relative, expectedContents] of outputs) {
    const target = path.join(packageRoot, relative);
    const actualContents = await readFile(target).catch(() => null);
    invariant(
      actualContents && actualContents.equals(expectedContents),
      `${posixPath(path.relative(root, target))}: generated documentation is stale. Run node scripts/project-package-docs.mjs.`,
    );
  }
}

async function writeProjection(packageRoot, outputs) {
  await rm(path.join(packageRoot, 'docs'), { recursive: true, force: true });
  await rm(path.join(packageRoot, 'README.md'), { force: true });
  for (const [relative, contents] of outputs) {
    const target = path.join(packageRoot, relative);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, contents);
  }
}

async function main() {
  await execFileAsync(process.execPath, [path.join(scriptDirectory, 'generate-lds-adoption-docs.mjs'), '--check'], {
    cwd: root,
    windowsHide: true,
  });
  const canonicalInputs = await assertCanonicalInputs();
  for (const definition of packageDefinitions) {
    const packageRoot = path.join(root, 'packages', definition.id);
    const outputs = await makePackageProjection(definition, canonicalInputs);
    if (check) await compareProjection(packageRoot, outputs);
    else await writeProjection(packageRoot, outputs);
  }
  console.log(`${check ? 'Validated' : 'Projected'} generated package documentation for Core, Theme, and Product packages.`);
}

