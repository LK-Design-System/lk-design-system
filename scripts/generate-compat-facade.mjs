import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const compatSourceRoot = path.join(root, 'packages', 'compat', 'src');
const roboticsExternalSurface = JSON.parse(await readFile(
  path.join(root, 'docs', 'references', 'package-split', 'ROBOTICS_EXTERNAL_SURFACE.json'),
  'utf8',
));
const classification = JSON.parse(await readFile(
  path.join(root, 'docs', 'references', 'wds', 'PUBLIC_EXPORT_CLASSIFICATION.json'),
  'utf8',
));
const productOwnedExports = new Set(
  (classification.groups ?? [])
    .filter((group) => group.ownerLayer === 'product')
    .flatMap((group) => group.exports ?? []),
);
const implementationPackages = [
  { id: 'core', layerEntry: 'core', name: '@lk-robotics/lds-core' },
  { id: 'theme', layerEntry: 'theme', name: '@lk-robotics/lds-theme' },
  { id: 'product', layerEntry: 'product', name: '@lk-robotics/lds-product' },
  {
    id: 'robotics-ui',
    layerEntry: 'robotics',
    name: '@lk-robotics/lds-robotics-ui',
    externalSurface: roboticsExternalSurface,
  },
];

const exportLinePattern = /^export\s+\{([^}]+)\}\s+from\s+'(?:\.\.\/|\.\/)(components\/[^']+)\.jsx';$/;
const header = [
  '// Generated by scripts/generate-compat-facade.mjs.',
  '// This compatibility package contains re-export facades only.',
  '',
];

function facadeSource(specifiers) {
  return `${[...header, ...specifiers.map((specifier) => `export * from '${specifier}';`)].join('\n')}\n`;
}

async function writeFacade(relativePath, source) {
  const jsPath = path.join(compatSourceRoot, `${relativePath}.js`);
  const declarationPath = path.join(compatSourceRoot, `${relativePath}.d.ts`);
  await mkdir(path.dirname(jsPath), { recursive: true });
  await Promise.all([
    writeFile(jsPath, source, 'utf8'),
    writeFile(declarationPath, source, 'utf8'),
  ]);
}

async function readPublicEntry(entryPath) {
  const source = await readFile(entryPath, 'utf8');
  const exportsByComponent = new Map();

  for (const line of source.split(/\r?\n/)) {
    if (!line.startsWith('export ')) continue;
    const match = line.match(exportLinePattern);
    if (!match) {
      if (line === "export * from '@lk-robotics/lds-robotics-ui';") continue;
      throw new Error(`${path.relative(root, entryPath)} contains an unsupported public export: ${line}`);
    }
    const [, exportClause, componentPath] = match;
    if (exportsByComponent.has(componentPath)) {
      throw new Error(`${path.relative(root, entryPath)} exports ${componentPath} more than once.`);
    }
    exportsByComponent.set(componentPath, exportClause.trim());
  }

  if (exportsByComponent.size === 0) {
    throw new Error(`${path.relative(root, entryPath)} has no public component exports.`);
  }

  return exportsByComponent;
}

function assertSamePublicSurface(expected, actual, label) {
  const errors = [];
  for (const [componentPath, exportClause] of expected) {
    if (!actual.has(componentPath)) errors.push(`missing ${componentPath}`);
    else if (actual.get(componentPath) !== exportClause) {
      errors.push(`${componentPath} exports { ${actual.get(componentPath)} }, expected { ${exportClause} }`);
    }
  }
  for (const componentPath of actual.keys()) {
    if (!expected.has(componentPath)) errors.push(`unexpected ${componentPath}`);
  }
  if (errors.length > 0) {
    throw new Error(`${label} does not preserve the legacy public surface:\n- ${errors.join('\n- ')}`);
  }
}

function readExternalSurface(surface, label) {
  if (surface?.package?.name !== '@lk-robotics/lds-robotics-ui' || !Array.isArray(surface.entries)) {
    throw new Error(`${label} is invalid.`);
  }
  const exportsByComponent = new Map();
  for (const entry of surface.entries) {
    if (typeof entry?.source !== 'string' || !Array.isArray(entry.exports) || entry.exports.length === 0) {
      throw new Error(`${label} has an invalid entry.`);
    }
    // The Robotics package preserves moved Product paths as compatibility
    // facades. They are not a second implementation surface.
    if (entry.exports.every((name) => productOwnedExports.has(name))) continue;
    if (exportsByComponent.has(entry.source)) throw new Error(`${label} duplicates ${entry.source}.`);
    exportsByComponent.set(entry.source, entry.exports.join(', '));
  }
  return exportsByComponent;
}

const packageSurfaces = [];
const implementationRootSurface = new Map();

for (const packageInfo of implementationPackages) {
  const implementationSurface = packageInfo.externalSurface
    ? readExternalSurface(packageInfo.externalSurface, `${packageInfo.name} external surface`)
    : await readPublicEntry(path.join(root, 'packages', packageInfo.id, 'src', 'index.js'));
  if (!packageInfo.externalSurface) {
    const legacyLayerEntry = path.join(root, 'src', `${packageInfo.layerEntry}.js`);
    const legacyLayerSurface = await readPublicEntry(legacyLayerEntry);
    assertSamePublicSurface(
      legacyLayerSurface,
      implementationSurface,
      `${packageInfo.name} against legacy ${packageInfo.layerEntry}`,
    );
  }

  for (const [componentPath, exportClause] of implementationSurface) {
    if (implementationRootSurface.has(componentPath)) {
      throw new Error(`${componentPath} is public from more than one implementation package.`);
    }
    implementationRootSurface.set(componentPath, exportClause);
  }
  packageSurfaces.push({ ...packageInfo, implementationSurface });
}

const legacyRootSurface = await readPublicEntry(path.join(root, 'src', 'index.js'));
for (const packageInfo of packageSurfaces.filter(({ externalSurface }) => externalSurface)) {
  for (const [componentPath, exportClause] of packageInfo.implementationSurface) {
    legacyRootSurface.set(componentPath, exportClause);
  }
}
assertSamePublicSurface(legacyRootSurface, implementationRootSurface, 'Compatibility root');

await rm(compatSourceRoot, { recursive: true, force: true });
await mkdir(compatSourceRoot, { recursive: true });

const rootSpecifiers = [];
let componentFacadeCount = 0;

for (const packageInfo of packageSurfaces) {
  rootSpecifiers.push(packageInfo.name);
  await writeFacade(packageInfo.layerEntry, facadeSource([packageInfo.name]));

  for (const componentPath of packageInfo.implementationSurface.keys()) {
    await writeFacade(
      componentPath,
      facadeSource([`${packageInfo.name}/${componentPath}`]),
    );
    componentFacadeCount += 1;
  }
}

await writeFacade('index', facadeSource(rootSpecifiers));

console.log(
  `Generated compatibility facade: 1 root, ${implementationPackages.length} layer entries, `
    + `${componentFacadeCount} component deep-import wrappers (JS and declarations).`,
);
