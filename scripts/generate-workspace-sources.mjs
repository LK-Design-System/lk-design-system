import { mkdir, readFile, copyFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const classification = JSON.parse(await readFile(path.join(root, 'docs/references/wds/PUBLIC_EXPORT_CLASSIFICATION.json'), 'utf8'));
const ownerAuthority = JSON.parse(await readFile(path.join(root, 'docs/references/architecture/OWNER_AUTHORITY_CONTRACT.json'), 'utf8'));
const layers = { core: 'core', theme: 'theme', product: 'product' };
const deprecatedReexports = ownerAuthority.compatibilityProjections?.deprecatedPackageReexports;

const owners = new Map();
for (const group of classification.groups ?? []) for (const name of group.exports ?? []) owners.set(name, group.ownerLayer);
const publicOwners = new Map();
const sourceOwners = new Map();
const rowsByLayer = new Map();

function parseEntry(text) {
  const rows = [];
  const re = /^export\s+\{\s*([^}]+)\s*\}\s+from\s+'([^']+)'/gm;
  for (const m of text.matchAll(re)) rows.push({ names: m[1].split(',').map((x) => x.trim()), source: m[2] });
  return rows;
}

for (const [layer] of Object.entries(layers)) {
  const rows = parseEntry(await readFile(path.join(root, 'src', `${layer}.js`), 'utf8'));
  rowsByLayer.set(layer, rows);
  for (const row of rows) {
    if (owners.get(row.names[0]) !== layer) continue;
    const rel = row.source.replace(/^\.\.\//, '').replaceAll('\\', '/');
    publicOwners.set(rel, layer);
    sourceOwners.set(rel, layer);
  }
}

for (const module of classification.internalModules ?? []) {
  sourceOwners.set(module.path.replaceAll('\\', '/'), module.ownerLayer);
}

function sourceOwner(rootRel) {
  const normalized = rootRel.replaceAll('\\', '/').replace(/^\.\//, '');
  const noExt = normalized.replace(/\.(jsx|js)$/, '');
  return sourceOwners.get(normalized)
    ?? sourceOwners.get(noExt)
    ?? sourceOwners.get(`${noExt}.js`)
    ?? sourceOwners.get(`${noExt}.jsx`);
}

for (const [layer, packageDir] of Object.entries(layers)) {
  const rows = rowsByLayer.get(layer) ?? [];
  const files = new Map();
  for (const row of rows) {
    const owner = owners.get(row.names[0]);
    if (owner !== layer) continue;
    const rel = row.source.replace(/^\.\.\//, '').replace(/\.jsx$/, '.jsx');
    files.set(rel, [...(files.get(rel) ?? []), ...row.names]);
  }
  const base = path.join(root, 'packages', packageDir);
  const generatedComponents = path.resolve(base, 'src', 'components');
  const packageRoot = `${path.resolve(base)}${path.sep}`;
  if (!generatedComponents.startsWith(packageRoot)) {
    throw new Error(`Refusing to clean generated sources outside package root: ${generatedComponents}`);
  }
  await rm(generatedComponents, { recursive: true, force: true });
  await mkdir(generatedComponents, { recursive: true });
  const entry = ['// Generated by scripts/generate-workspace-sources.mjs.', ''];
  for (const module of classification.internalModules ?? []) {
    if (module.ownerLayer !== layer) continue;
    const src = path.join(root, module.path);
    const target = path.join(base, 'src', module.path);
    await mkdir(path.dirname(target), { recursive: true });
    await copyFile(src, target);
    if (src.endsWith('.js')) {
      try {
        await copyFile(src.replace(/\.js$/, '.d.ts'), target.replace(/\.js$/, '.d.ts'));
      } catch (error) {
        if (error?.code !== 'ENOENT') throw error;
      }
    }
    await copyHelpers(src, base, layer, new Set());
    await rewriteImports(target, layer, base);
  }
  for (const [rel, names] of [...files].sort(([a], [b]) => a.localeCompare(b))) {
    const src = path.join(root, 'components', rel.replace(/^components[\\/]/, ''));
    const targetRel = rel.replace(/^components[\\/]/, '');
    const target = path.join(base, 'src', 'components', targetRel);
    await mkdir(path.dirname(target), { recursive: true });
    await copyFile(src, target);
    const dts = src.replace(/\.jsx$/, '.d.ts');
    const declarationTarget = target.replace(/\.jsx$/, '.d.ts');
    await copyFile(dts, declarationTarget);
    await copyHelpers(src, base, layer, new Set());
    await rewriteImports(target, layer, base);
    await rewriteImports(declarationTarget, layer, base);
    entry.push(`export { ${[...new Set(names)].join(', ')} } from './components/${targetRel}';`);
  }
  if (deprecatedReexports?.status === 'active' && deprecatedReexports.sourceLayer === layer) {
    const targetPackage = `@lk-design-system/lds-${layers[deprecatedReexports.targetLayer]}`;
    const migration = `Import from ${targetPackage}. This ${layer} compatibility re-export is supported through 0.1.x and may be removed in 0.2.0.`;
    for (const compatibility of deprecatedReexports.entries ?? []) {
      const modulePath = compatibility.module.replaceAll('\\', '/');
      const targetRel = modulePath.replace(/^components\//, '');
      const target = path.join(base, 'src', 'components', targetRel);
      const targetSpecifier = `${targetPackage}/${modulePath.replace(/\.(jsx|js)$/, '')}`;
      const exportClause = compatibility.exports?.length
        ? `export { ${compatibility.exports.join(', ')} } from '${targetSpecifier}';`
        : `export * from '${targetSpecifier}';`;
      const source = `/** @deprecated ${migration} */\n${exportClause}\n`;
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, source);
      const declarationTarget = target.replace(/\.(jsx|js)$/, '.d.ts');
      await writeFile(declarationTarget, source);
      if (compatibility.exports?.length) {
        entry.push(`/** @deprecated ${migration} */`);
        entry.push(`export { ${compatibility.exports.join(', ')} } from './components/${targetRel}';`);
      }
    }
  }
  await writeFile(path.join(base, 'src', 'index.js'), `${entry.join('\n')}\n`);
  await writeFile(path.join(base, 'src', 'index.d.ts'), `${entry.join('\n')}\n`);
  await writeFile(path.join(base, 'styles.css'), `/* ${packageDir} package style entry; populated during Wave 1 CSS split. */\n`);
}

async function copyHelpers(source, base, layer, seen) {
  if (seen.has(source)) return;
  seen.add(source);
  const text = await readFile(source, 'utf8');
  const re = /(?:from\s+|import\s*\(\s*)(['"])(\.\.?\/[^'"\n]+)\1/g;
  for (const match of text.matchAll(re)) {
    const resolved = path.resolve(path.dirname(source), match[2]);
    const candidates = [resolved, `${resolved}.js`, `${resolved}.jsx`];
    let helper;
    for (const candidate of candidates) { try { await readFile(candidate); helper = candidate; break; } catch {} }
    if (!helper) continue;
    const rel = path.relative(path.join(root, 'components'), helper).replaceAll('\\', '/');
    const owner = sourceOwner(`components/${rel}`);
    if (owner && owner !== layer) continue;
    const target = path.join(base, 'src', 'components', rel);
    await mkdir(path.dirname(target), { recursive: true });
    await copyFile(helper, target);
    if (helper.endsWith('.js')) {
      const declaration = helper.replace(/\.js$/, '.d.ts');
      try {
        await copyFile(declaration, target.replace(/\.js$/, '.d.ts'));
      } catch (error) {
        if (error?.code !== 'ENOENT') throw error;
      }
    }
    await copyHelpers(helper, base, layer, seen);
    // Helpers can import a public component owned by another package too.
    // Rewrite them after their local dependency graph has been copied so the
    // workspace package never retains an accidental source-path dependency.
    await rewriteImports(target, layer, base);
  }
}

async function rewriteImports(target, layer, base) {
  const original = await readFile(target, 'utf8');
  const importRe = /(from\s+['"]|import\s*\(\s*['"])(\.\.?\/[^'"\n]+)(['"])/g;
  const text = original.replace(importRe, (all, prefix, spec, suffix) => {
    const noExt = spec.replace(/\.(jsx|js)$/, '');
    const sourceRel = path.posix.normalize(path.posix.join(path.posix.dirname(path.relative(path.join(base, 'src'), target).replaceAll('\\', '/')), noExt));
    const rootRel = sourceRel.startsWith('components/') ? sourceRel : `components/${sourceRel.replace(/^\.\//, '')}`;
    const owner = sourceOwner(rootRel);
    if (owner && owner !== layer) {
      const packageName = `@lk-design-system/lds-${layers[owner]}`;
      return `${prefix}${packageName}/${rootRel}${suffix}`;
    }
    return all;
  });
  if (text !== original) await writeFile(target, text);
}

console.log('Generated workspace implementation sources for core, theme, and product; Robotics UI is external.');
