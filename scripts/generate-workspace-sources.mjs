import { mkdir, readFile, copyFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const classification = JSON.parse(await readFile(path.join(root, 'docs/references/wds/PUBLIC_EXPORT_CLASSIFICATION.json'), 'utf8'));
const layers = { core: 'core', theme: 'theme', product: 'product', robotics: 'robotics-ui' };

const owners = new Map();
for (const group of classification.groups ?? []) for (const name of group.exports ?? []) owners.set(name, group.ownerLayer);
const publicOwners = new Map();

function parseEntry(text) {
  const rows = [];
  const re = /^export\s+\{\s*([^}]+)\s*\}\s+from\s+'([^']+)'/gm;
  for (const m of text.matchAll(re)) rows.push({ names: m[1].split(',').map((x) => x.trim()), source: m[2] });
  return rows;
}

for (const [layer, packageDir] of Object.entries(layers)) {
  const rows = parseEntry(await readFile(path.join(root, 'src', `${layer}.js`), 'utf8'));
  const files = new Map();
  for (const row of rows) {
    const owner = owners.get(row.names[0]);
    if (owner !== layer) continue;
    const rel = row.source.replace(/^\.\.\//, '').replace(/\.jsx$/, '.jsx');
    files.set(rel, [...(files.get(rel) ?? []), ...row.names]);
    publicOwners.set(rel, layer);
  }
  const base = path.join(root, 'packages', packageDir);
  await mkdir(path.join(base, 'src', 'components'), { recursive: true });
  const entry = ['// Generated by scripts/generate-workspace-sources.mjs.', ''];
  for (const [rel, names] of [...files].sort(([a], [b]) => a.localeCompare(b))) {
    const src = path.join(root, 'components', rel.replace(/^components[\\/]/, ''));
    const targetRel = rel.replace(/^components[\\/]/, '');
    const target = path.join(base, 'src', 'components', targetRel);
    await mkdir(path.dirname(target), { recursive: true });
    await copyFile(src, target);
    const dts = src.replace(/\.jsx$/, '.d.ts');
    await copyFile(dts, target.replace(/\.jsx$/, '.d.ts'));
    await copyHelpers(src, base, layer, new Set());
    await rewriteImports(target, layer, base);
    entry.push(`export { ${[...new Set(names)].join(', ')} } from './components/${targetRel}';`);
  }
  await writeFile(path.join(base, 'src', 'index.js'), `${entry.join('\n')}\n`);
  await writeFile(path.join(base, 'src', 'index.d.ts'), `${entry.join('\n')}\n`);
  await writeFile(path.join(base, 'styles.css'), `/* ${packageDir} package style entry; populated during Wave 1 CSS split. */\n`);
}

async function copyHelpers(source, base, layer, seen) {
  if (seen.has(source)) return;
  seen.add(source);
  const text = await readFile(source, 'utf8');
  const re = /(?:from\s+|import\s*\(\s*)(['"])(\.\.?\/[^'"\n]+)\1/g;
  for (const match of text.matchAll(re)) {
    const resolved = path.resolve(path.dirname(source), match[2]);
    const candidates = [resolved, `${resolved}.js`, `${resolved}.jsx`];
    let helper;
    for (const candidate of candidates) { try { await readFile(candidate); helper = candidate; break; } catch {} }
    if (!helper) continue;
    const rel = path.relative(path.join(root, 'components'), helper).replaceAll('\\', '/');
    const owner = publicOwners.get(`components/${rel.replace(/\.(js|jsx)$/, '.jsx')}`);
    if (owner && owner !== layer) continue;
    const target = path.join(base, 'src', 'components', rel);
    await mkdir(path.dirname(target), { recursive: true });
    await copyFile(helper, target);
    await copyHelpers(helper, base, layer, seen);
    // Helpers can import a public component owned by another package too.
    // Rewrite them after their local dependency graph has been copied so the
    // workspace package never retains an accidental source-path dependency.
    await rewriteImports(target, layer, base);
  }
}

async function rewriteImports(target, layer, base) {
  let text = await readFile(target, 'utf8');
  const importRe = /(from\s+['"]|import\s*\(\s*['"])(\.\.?\/[^'"\n]+)(['"])/g;
  text = text.replace(importRe, (all, prefix, spec, suffix) => {
    const noExt = spec.replace(/\.(jsx|js)$/, '');
    const sourceRel = path.posix.normalize(path.posix.join(path.posix.dirname(path.relative(path.join(base, 'src'), target).replaceAll('\\', '/')), noExt));
    const rootRel = sourceRel.startsWith('components/') ? sourceRel : `components/${sourceRel.replace(/^\.\//, '')}`;
    const owner = publicOwners.get(rootRel) || publicOwners.get(`${rootRel}.jsx`);
    if (owner && owner !== layer) {
      const packageName = `@lk-robotics/lds-${layers[owner]}`;
      return `${prefix}${packageName}/${rootRel}${suffix}`;
    }
    return all;
  });
  await writeFile(target, text);
}

console.log('Generated workspace implementation sources for core, theme, product, and robotics-ui.');
