function invariant(condition, message) {
  if (!condition) throw new Error(message);
}

async function exists(file) {
  try {
    await access(file);
    return true;
  } catch {
    return false;
  }
}

function posixPath(value) {
  return value.replaceAll('\\', '/');
}

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}

async function readJson(file) {
  return JSON.parse(await readFile(file, 'utf8'));
}

async function walkFiles(directory) {
  if (!(await exists(directory))) return [];
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walkFiles(full));
    else files.push(full);
  }
  return files;
}

async function inventory(directory) {
  const files = await walkFiles(directory);
  const rows = [];
  let bytes = 0;
  for (const file of files.sort((left, right) => left.localeCompare(right))) {
    const contents = await readFile(file);
    const relative = posixPath(path.relative(directory, file));
    bytes += contents.byteLength;
    rows.push(`${relative}|${contents.byteLength}|${sha256(contents)}`);
  }
  return { fileCount: files.length, bytes, sha256: sha256(rows.join('\n')) };
}

function run(command, args, options = {}) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, {
      cwd: options.cwd ?? root,
      env: process.env,
      shell: false,
      windowsHide: true,
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    let stdout = '';
    let stderr = '';
    child.stdout.setEncoding('utf8');
    child.stderr.setEncoding('utf8');
    child.stdout.on('data', (chunk) => { stdout += chunk; });
    child.stderr.on('data', (chunk) => { stderr += chunk; });
    child.on('error', reject);
    child.on('close', (code) => {
      if (code === 0) resolve({ stdout, stderr });
      else reject(new Error(`${command} ${args.join(' ')} failed.\n${stderr || stdout}`.trim()));
    });
  });
}

function formatAjvErrors(errors) {
  return (errors ?? []).map(({ instancePath, message }) => `${instancePath || '/'} ${message}`).join('; ');
}

function expectedLdsMetadata(definition) {
  return {
    schemaVersion: 1,
    layer: definition.layer,
    manifest: './docs/manifest.json',
    llms: './docs/llms.txt',
    adoptionChecklist: './docs/adoption-checklist.json',
    adoptionReportSchema: './docs/adoption-report.schema.json',
    storybook: `${publicRoot}${definition.storybookPath}`,
  };
}

function checkRelativeLinks(contents, file, packageRoot) {
  for (const match of contents.matchAll(/\[[^\]]*\]\(([^)]+)\)/g)) {
    const raw = match[1].startsWith('<') && match[1].endsWith('>')
      ? match[1].slice(1, -1)
      : match[1];
    if (/^(?:https?:|mailto:|tel:|data:|#)/i.test(raw)) continue;
    const pathname = raw.split(/[?#]/, 1)[0];
    if (!pathname) continue;
    let decoded;
    try {
      decoded = decodeURIComponent(pathname);
    } catch {
      throw new Error(`${posixPath(path.relative(root, file))}: malformed link ${raw}.`);
    }
    const target = path.resolve(path.dirname(file), decoded);
    const relative = path.relative(packageRoot, target);
    invariant(
      !relative.startsWith('..') && !path.isAbsolute(relative),
      `${posixPath(path.relative(root, file))}: relative link escapes the package: ${raw}.`,
    );
    invariant(
      requireExists(target),
      `${posixPath(path.relative(root, file))}: broken relative link ${raw}.`,
    );
  }
}

function requireExists(file) {
  try {
    return Boolean(globalThis.__packageDocFiles?.has(path.resolve(file)));
  } catch {
    return false;
  }
}

function withoutReferenceProjection(contract) {
  return {
    ...contract,
    facets: contract.facets.map((facet) => ({ ...facet, references: [] })),
    componentMapping: { ...contract.componentMapping, references: [] },
  };
}

async function validateMachineReferences(contract, definition, packageRoot) {
  const references = [
    ...contract.facets.flatMap((facet) => facet.references),
    ...contract.componentMapping.references,
  ];
  const checklistPath = path.join(packageRoot, 'docs', 'adoption-checklist.json');
  for (const reference of references) {
    if (/^https:\/\//.test(reference)) continue;
    let target;
    if (reference.startsWith('@lk-design-system/lds-core/')) {
      const relative = reference.slice('@lk-design-system/lds-core/'.length);
      target = path.join(root, 'packages', 'core', relative);
    } else {
      target = path.resolve(path.dirname(checklistPath), reference);
      const relative = path.relative(packageRoot, target);
      invariant(
        !relative.startsWith('..') && !path.isAbsolute(relative),
        `${definition.name}: machine reference escapes its package without an owner specifier: ${reference}.`,
      );
    }
    invariant(await exists(target), `${definition.name}: unresolved machine reference ${reference}.`);
  }
}

async function validatePackage(
  definition,
  canonicalContract,
  canonicalContractSchema,
  canonicalReportSchema,
  canonicalFoundationSlugs,
  validateContract,
  validateReport,
) {
  const packageRoot = path.join(root, 'packages', definition.id);
  const manifest = await readJson(path.join(packageRoot, 'package.json'));
  invariant(manifest.name === definition.name, `${definition.id}: unexpected package name ${manifest.name}.`);
  for (const published of ['README.md', 'docs']) {
    invariant(manifest.files?.includes(published), `${definition.name}: files must include ${published}.`);
  }
  for (const [subpath, target] of Object.entries(requiredExports)) {
    invariant(manifest.exports?.[subpath] === target, `${definition.name}: export ${subpath} must target ${target}.`);
  }
  const expectedMetadata = expectedLdsMetadata(definition);
  invariant(isDeepStrictEqual(manifest.lds, expectedMetadata), `${definition.name}: lds metadata is stale or incomplete.`);
  invariant(manifest.homepage === expectedMetadata.storybook, `${definition.name}: homepage must lead to its live LDS documentation.`);

  const readmePath = path.join(packageRoot, 'README.md');
  const readme = await readFile(readmePath, 'utf8');
  invariant(readme.startsWith(generatedMarker), `${definition.name}: README is not a generated package projection.`);
  invariant(readme.includes(`${definition.name}/llms.txt`), `${definition.name}: README does not expose the AI entrypoint.`);
  invariant(readme.includes(`${definition.name}/adoption-checklist.json`), `${definition.name}: README does not expose the adoption contract.`);

  for (const relative of requiredDocFiles) {
    invariant(await exists(path.join(packageRoot, 'docs', relative)), `${definition.name}: docs/${relative} is missing.`);
  }
  const packagedContract = await readJson(path.join(packageRoot, 'docs', 'adoption-checklist.json'));
  const packagedContractSchema = await readJson(path.join(packageRoot, 'docs', 'LDS_UI_ADOPTION_CONTRACT.schema.json'));
  const packagedReportSchema = await readJson(path.join(packageRoot, 'docs', 'adoption-report.schema.json'));
  const packagedReportExample = await readJson(path.join(packageRoot, 'docs', 'adoption-report.example.json'));
  invariant(
    isDeepStrictEqual(withoutReferenceProjection(packagedContract), withoutReferenceProjection(canonicalContract)),
    `${definition.name}: adoption contract decisions differ from the canonical source.`,
  );
  invariant(isDeepStrictEqual(packagedContractSchema, canonicalContractSchema), `${definition.name}: adoption contract schema differs from the canonical source.`);
  invariant(isDeepStrictEqual(packagedReportSchema, canonicalReportSchema), `${definition.name}: adoption report schema differs from the canonical source.`);
  invariant(validateContract(packagedContract), `${definition.name}: packaged adoption contract is invalid: ${formatAjvErrors(validateContract.errors)}`);
  invariant(validateReport(packagedReportExample), `${definition.name}: packaged report example is invalid: ${formatAjvErrors(validateReport.errors)}`);
  invariant(
    packagedContract.$schema === `./${path.basename('LDS_UI_ADOPTION_CONTRACT.schema.json')}`,
    `${definition.name}: adoption contract must resolve its packaged schema relatively.`,
  );
  invariant(packagedReportExample.$schema === './adoption-report.schema.json', `${definition.name}: report example schema link is not package-relative.`);
  await validateMachineReferences(packagedContract, definition, packageRoot);

  const docsManifest = await readJson(path.join(packageRoot, 'docs', 'manifest.json'));
  invariant(docsManifest.schemaVersion === 1 && docsManifest.kind === 'lds-package-documentation', `${definition.name}: invalid documentation manifest identity.`);
  invariant(
    isDeepStrictEqual(docsManifest.package, { name: definition.name, version: manifest.version, layer: definition.layer }),
    `${definition.name}: documentation manifest package identity drift.`,
  );
  invariant(docsManifest.adoption.contractKind === canonicalContract.kind, `${definition.name}: contract kind drift.`);
  invariant(docsManifest.adoption.contractVersion === canonicalContract.contractVersion, `${definition.name}: contract version drift.`);
  invariant(docsManifest.adoption.invariant === canonicalContract.invariant, `${definition.name}: completion invariant drift.`);
  invariant(isDeepStrictEqual(docsManifest.adoption.facetIds, facetIds), `${definition.name}: adoption facet coverage drift.`);
  invariant(docsManifest.adoption.componentMappingRequired === true, `${definition.name}: component mapping must remain an additional requirement.`);
  invariant(isDeepStrictEqual(docsManifest.adoption.verdicts, canonicalContract.verdicts), `${definition.name}: adoption verdict drift.`);
  invariant(docsManifest.source?.ref === `lds-v${manifest.version}`, `${definition.name}: documentation source ref must be release-version pinned.`);
  invariant(
    isDeepStrictEqual(docsManifest.entrypoints, {
      llms: './llms.txt',
      adoptionChecklist: './adoption-checklist.json',
      adoptionReportSchema: './adoption-report.schema.json',
      adoptionReportExample: './adoption-report.example.json',
      adoptionWorkflow: './adoption-workflow.md',
      ...(definition.id === 'core' ? { agentSkill: './agent-skills/lds-ui/SKILL.md' } : {}),
    }),
    `${definition.name}: documentation entrypoints drift.`,
  );
  const expectedFoundations = definition.foundations === 'all' ? canonicalFoundationSlugs : definition.foundations;
  invariant(isDeepStrictEqual(docsManifest.foundations, expectedFoundations), `${definition.name}: Foundation projection drift.`);
  invariant(docsManifest.publicDocs.storybook === expectedMetadata.storybook, `${definition.name}: live docs URL drift.`);
  const publicDocsBase = definition.id === 'core' ? publicRoot : `${publicRoot}packages/${definition.id}/`;
  invariant(docsManifest.publicDocs.llms === `${publicDocsBase}llms.txt`, `${definition.name}: public llms URL drift.`);
  invariant(
    docsManifest.publicDocs.designSystem === (definition.id === 'core' ? `${publicRoot}design-system.json` : `${publicDocsBase}manifest.json`),
    `${definition.name}: public design-system manifest URL drift.`,
  );
  invariant(docsManifest.publicDocs.adoptionChecklist === `${publicDocsBase}adoption-checklist.json`, `${definition.name}: public checklist URL drift.`);
  invariant(docsManifest.publicDocs.adoptionReportSchema === `${publicDocsBase}adoption-report.schema.json`, `${definition.name}: public report schema URL drift.`);
  invariant(docsManifest.publicDocs.adoptionReportExample === `${publicDocsBase}adoption-report.example.json`, `${definition.name}: public report example URL drift.`);

  for (const resource of ['tokens', 'assets']) {
    const actualInventory = await inventory(path.join(packageRoot, resource));
    invariant(
      isDeepStrictEqual(docsManifest.resources?.[resource], actualInventory),
      `${definition.name}: ${resource} inventory count, bytes, or hash drift. Regenerate package docs.`,
    );
  }

  const documentFiles = (await walkFiles(path.join(packageRoot, 'docs')))
    .map((file) => posixPath(path.relative(path.join(packageRoot, 'docs'), file)))
    .filter((file) => file !== 'manifest.json')
    .sort();
  const records = docsManifest.documents ?? [];
  const recordPaths = records.map(({ path: file }) => file).sort();
  invariant(isDeepStrictEqual(documentFiles, recordPaths), `${definition.name}: manifest document file set drift.`);
  for (const record of records) {
    const contents = await readFile(path.join(packageRoot, 'docs', record.path));
    invariant(sha256(contents) === record.sha256, `${definition.name}: docs/${record.path} hash drift.`);
    invariant(Array.isArray(record.sources) && record.sources.length > 0, `${definition.name}: docs/${record.path} has no canonical provenance.`);
  }
  for (const source of docsManifest.source?.documents ?? []) {
    const contents = await readFile(path.join(root, source.path));
    invariant(sha256(contents) === source.sha256, `${definition.name}: canonical source hash drift for ${source.path}.`);
  }

  const allPackageFiles = await walkFiles(packageRoot);
  globalThis.__packageDocFiles = new Set(allPackageFiles.map((file) => path.resolve(file)));
  for (const file of [readmePath, ...allPackageFiles.filter((candidate) => /\.(?:md|txt)$/i.test(candidate))]) {
    const contents = await readFile(file, 'utf8');
    invariant(
      !/file:\/\/|(?:^|[\s(<"'])[A-Za-z]:[\\/]/m.test(contents),
      `${definition.name}: generated docs expose a machine-local path in ${posixPath(path.relative(packageRoot, file))}.`,
    );
    checkRelativeLinks(contents, file, packageRoot);
  }
  delete globalThis.__packageDocFiles;
}

async function validateStorybookProjection() {
  const configUrl = `${pathToFileURL(path.join(root, '.storybook', 'main.js')).href}?package-doc-check=${Date.now()}`;
  const { default: config } = await import(configUrl);
  for (const [from, to] of publicProjection) {
    invariant(
      config.staticDirs?.some((entry) => entry?.from === from && entry?.to === to),
      `.storybook/main.js must publish ${from} at ${to}.`,
    );
    invariant(await exists(path.resolve(root, '.storybook', from)), `Storybook public projection source is missing: ${from}.`);
  }
}

async function main() {
  await run(process.execPath, [path.join(scriptDirectory, 'project-package-docs.mjs'), '--check']);

  const canonicalContract = await readJson(path.join(root, 'docs', 'references', 'adoption', 'LDS_UI_ADOPTION_CONTRACT.json'));
  const canonicalContractSchema = await readJson(path.join(root, 'docs', 'references', 'adoption', 'LDS_UI_ADOPTION_CONTRACT.schema.json'));
  const canonicalReportSchema = await readJson(path.join(root, 'docs', 'references', 'adoption', 'LDS_UI_ADOPTION_REPORT.schema.json'));
  const foundationContent = await readJson(path.join(root, 'docs', 'foundations', 'foundation-content.json'));
  const canonicalFoundationSlugs = foundationContent.foundations.map(({ slug }) => slug);
  invariant(
    isDeepStrictEqual(canonicalContract.facets.map(({ id }) => id), facetIds),
    'Canonical adoption facet order or identity drift.',
  );

  const ajv = new Ajv2020({ allErrors: true, strict: true });
  addFormats(ajv);
  const validateContract = ajv.compile(canonicalContractSchema);
  const validateReport = ajv.compile(canonicalReportSchema);

  for (const definition of packageDefinitions) {
    await validatePackage(
      definition,
      canonicalContract,
      canonicalContractSchema,
      canonicalReportSchema,
      canonicalFoundationSlugs,
      validateContract,
      validateReport,
    );
  }
  await validateStorybookProjection();
  console.log('Validated generated package docs: canonical adoption/schema projection, full Core context, Theme/Product deltas, exports, inventories, hashes, links, and Storybook public endpoints.');
}

main().catch((error) => {
  console.error(error.stack ?? error.message);
  process.exitCode = 1;
});
