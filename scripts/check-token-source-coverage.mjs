import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const root = process.cwd();
const sourcePath = path.join(root, 'tokens', 'source.json');
const update = process.argv.includes('--update');

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function collectCssRefs(value, refs = new Set()) {
  if (Array.isArray(value)) {
    value.forEach((item) => collectCssRefs(item, refs));
    return refs;
  }
  if (!value || typeof value !== 'object') return refs;
  if (typeof value.css === 'string') refs.add(value.css);
  if (Array.isArray(value.css)) value.css.forEach((css) => refs.add(css));
  for (const [key, child] of Object.entries(value)) {
    if (key !== 'runtimeCoverage') collectCssRefs(child, refs);
  }
  return refs;
}

function declarations(css) {
  const result = [];
  for (const match of css.matchAll(/(--[a-zA-Z0-9_-]+)\s*:\s*([^;]+);/g)) {
    result.push({ css: match[1], value: match[2].trim().replace(/\s+/g, ' ') });
  }
  return result;
}

const source = JSON.parse(await readFile(sourcePath, 'utf8'));
const structuredRefs = collectCssRefs(source);
const runtimeFiles = source.metadata.runtimeCssFiles;
const declarationMap = new Map();

for (const file of runtimeFiles) {
  const css = await readFile(path.join(root, file), 'utf8');
  for (const declaration of declarations(css)) {
    const existing = declarationMap.get(declaration.css);
    if (existing) {
      existing.files.add(file);
      existing.values.add(declaration.value);
    } else {
      declarationMap.set(declaration.css, {
        css: declaration.css,
        files: new Set([file]),
        values: new Set([declaration.value]),
      });
    }
  }
}

const unstructured = [...declarationMap.values()]
  .filter(({ css }) => !structuredRefs.has(css))
  .map(({ css, files, values }) => ({
    css,
    files: [...files].sort(),
    values: [...values].sort(),
    classification: 'runtime-projection',
    reason: 'Runtime variable is not yet promoted into a primitive, semantic, or component token object; it remains explicitly inventoried and drift-checked.',
  }))
  .sort((a, b) => a.css.localeCompare(b.css));

if (update) {
  source.runtimeCoverage = {
    description: 'Complete reverse inventory for runtime CSS declarations that are not represented by structured token objects. Generated by scripts/check-token-source-coverage.mjs --update.',
    tokens: unstructured,
  };
  await writeFile(sourcePath, `${JSON.stringify(source, null, 2)}\n`);
  console.log(`Updated runtime token reverse coverage: ${declarationMap.size} declarations, ${structuredRefs.size} structured refs, ${unstructured.length} runtime projections.`);
  process.exit(0);
}

const inventory = source.runtimeCoverage?.tokens;
assert(Array.isArray(inventory), 'tokens/source.json must contain generated runtimeCoverage.tokens.');
const inventoryMap = new Map(inventory.map((item) => [item.css, item]));
const unmanaged = unstructured.filter(({ css }) => !inventoryMap.has(css));
const stale = inventory.filter(({ css }) => !declarationMap.has(css) || structuredRefs.has(css));
const drifted = unstructured.filter((current) => {
  const recorded = inventoryMap.get(current.css);
  return recorded && JSON.stringify(recorded) !== JSON.stringify(current);
});

assert(unmanaged.length === 0, `Runtime CSS declarations missing from tokens/source.json reverse coverage:\n- ${unmanaged.map(({ css }) => css).join('\n- ')}`);
assert(stale.length === 0, `Stale runtime coverage entries:\n- ${stale.map(({ css }) => css).join('\n- ')}`);
assert(drifted.length === 0, `Runtime coverage value/file drift:\n- ${drifted.map(({ css }) => css).join('\n- ')}`);
assert(inventory.length === unstructured.length, `Runtime coverage count mismatch: ${inventory.length} recorded, ${unstructured.length} current.`);

console.log(`Validated reverse token coverage: ${declarationMap.size} runtime declarations, ${declarationMap.size - unstructured.length} structured, ${unstructured.length} explicit runtime projections, 0 unmanaged.`);
